export const normalizeLang = (lang?: string | null): StratosLang => {
  return AVAILABLE_LANGS.includes(lang as StratosLang) ? (lang as StratosLang) : "ES";
};

export const tx = (lang: string | null | undefined, key: string) => {
  const safeLang = normalizeLang(lang);
  return UI_TEXT?.[safeLang]?.[key] || UI_TEXT.ES[key] || key;
};

export const nextLanguage = (lang: string | null | undefined): StratosLang => {
  const safeLang = normalizeLang(lang);
  const currentIndex = AVAILABLE_LANGS.indexOf(safeLang);
  return AVAILABLE_LANGS[(currentIndex + 1) % AVAILABLE_LANGS.length];
};

export const isRTL = (lang: string | null | undefined) => normalizeLang(lang) === "AR";

export const getDocumentLang = (lang: string | null | undefined) => {
  return normalizeLang(lang).toLowerCase();
};

export const getDocumentDir = (lang: string | null | undefined) => {
  return isRTL(lang) ? "rtl" : "ltr";
};